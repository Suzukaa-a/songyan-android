package app.songyan.ime.content

/** One emoji of the catalog: the base form, its skin-tone variants and the words that find it. */
data class EmojiEntry(
    val emoji: String,
    val zhKeywords: List<String> = emptyList(),
    val enKeywords: List<String> = emptyList(),
    /** Skin-tone forms of [emoji], light to dark; empty when the emoji has none. */
    val variants: List<String> = emptyList(),
)

/** A browsing category of the emoji panel; [id] is the Unicode group name. */
data class EmojiCategory(
    val id: String,
    val emojis: List<EmojiEntry>,
)

/**
 * The emoji the panel offers, grouped and searchable.
 *
 * The data file is generated by `scripts/generate-emoji-data.py` (Unicode emoji data and CLDR
 * annotations): one `@Group` line per category, then one tab-separated line per emoji with its
 * Chinese and English keywords and skin-tone variants. Parsing is tolerant: a short or blank line is
 * skipped, never fatal, so a damaged line costs one emoji and not the panel.
 */
class EmojiCatalog(
    val categories: List<EmojiCategory>,
) {
    private val all: List<EmojiEntry> by lazy { categories.flatMap { it.emojis } }

    /**
     * The catalog limited to emoji [keep] accepts: a base form that is refused takes its whole entry
     * with it, a refused variant only itself. Categories left empty are dropped.
     */
    fun filtered(keep: (String) -> Boolean): EmojiCatalog =
        EmojiCatalog(
            categories.mapNotNull { category ->
                val kept =
                    category.emojis
                        .filter { keep(it.emoji) }
                        .map { entry -> entry.copy(variants = entry.variants.filter(keep)) }
                if (kept.isEmpty()) null else category.copy(emojis = kept)
            },
        )

    /** The entry whose base or variant form is [emoji] (what a recent list stores), or null. */
    fun find(emoji: String): EmojiEntry? = all.firstOrNull { it.emoji == emoji || emoji in it.variants }

    /**
     * Emoji whose keywords match [query], best matches first and catalog order inside a tier: an exact
     * keyword, then a keyword that starts with the query, then one that contains it. A single Latin
     * letter matches nothing, since it would match half the catalog.
     */
    fun search(
        query: String,
        limit: Int = DEFAULT_SEARCH_LIMIT,
    ): List<EmojiEntry> {
        val needle = query.trim().lowercase()
        if (needle.isEmpty() || limit <= 0) return emptyList()
        if (needle.length == 1 && needle[0].code < ASCII_LIMIT) return emptyList()
        val ranked = ArrayList<Pair<Int, EmojiEntry>>()
        for (entry in all) {
            val rank = rank(entry, needle)
            if (rank >= 0) ranked += rank to entry
        }
        // A stable sort keeps the catalog order inside a tier.
        return ranked.sortedBy { it.first }.take(limit).map { it.second }
    }

    private fun rank(
        entry: EmojiEntry,
        needle: String,
    ): Int {
        var best = -1

        fun offer(rank: Int) {
            if (best < 0 || rank < best) best = rank
        }
        for (word in entry.zhKeywords) {
            when {
                word == needle -> offer(0)
                word.startsWith(needle) -> offer(1)
                word.contains(needle) -> offer(2)
            }
        }
        for (word in entry.enKeywords) {
            val lower = word.lowercase()
            when {
                lower == needle -> offer(0)
                lower.startsWith(needle) -> offer(1)
                // Inside an English word a short fragment is noise (`an` in `banana`).
                needle.length >= MIN_CONTAINS_LENGTH && lower.contains(needle) -> offer(2)
            }
        }
        return best
    }

    companion object {
        const val DEFAULT_SEARCH_LIMIT = 60
        private const val ASCII_LIMIT = 128
        private const val MIN_CONTAINS_LENGTH = 3

        /** A data line has at least the emoji and its Chinese keywords. */
        private const val MIN_FIELDS = 2

        /** Parses the generated data file. */
        fun parse(lines: Sequence<String>): EmojiCatalog {
            val categories = ArrayList<EmojiCategory>()
            var group: String? = null
            var entries = ArrayList<EmojiEntry>()

            fun close() {
                val id = group ?: return
                if (entries.isNotEmpty()) categories += EmojiCategory(id, entries)
                entries = ArrayList()
            }
            for (line in lines) {
                when {
                    line.isBlank() || line.startsWith("#") -> Unit
                    line.startsWith("@") -> {
                        close()
                        group = line.substring(1).trim()
                    }
                    else -> {
                        val fields = line.split('\t')
                        if (fields.size < MIN_FIELDS) continue
                        val emoji = fields.first().takeIf { it.isNotEmpty() } ?: continue
                        entries +=
                            EmojiEntry(
                                emoji = emoji,
                                zhKeywords = words(fields.getOrNull(1)),
                                enKeywords = words(fields.getOrNull(2)),
                                variants =
                                    fields
                                        .getOrNull(3)
                                        .orEmpty()
                                        .split(' ')
                                        .filter { it.isNotEmpty() },
                            )
                    }
                }
            }
            close()
            return EmojiCatalog(categories)
        }

        private fun words(field: String?): List<String> = field.orEmpty().split('|').filter { it.isNotBlank() }
    }
}
